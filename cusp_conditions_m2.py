#!/usr/bin/env python3
"""Exact cusp Frobenius/Galois permutations for X_1(2,N).

Tate labels are Q=(a,b) in (Z/N)^2, P=(c,d) in (Z/2)^2,
with Q primitive and cb-da=1 mod2. Quotient by upper unipotents and
simultaneous sign. Cyclotomic t acts on the multiplicative coordinates
a,c; Frobenius is t=p. A residue q is admissible for complement degree k
when q maps every cusp in a Frobenius orbit of length <=k into that orbit.
"""
from collections import Counter
from math import gcd
from pathlib import Path
import json

HERE=Path(__file__).resolve().parent
CASES=[(22,3),(24,5),(26,3),(28,3),(30,7)]

def compute(n,p,degree=6):
    labels={(a,b,c,d) for a in range(n) for b in range(n)
            if gcd(gcd(a,b),n)==1 for c in range(2) for d in range(2)
            if (c*b-d*a)%2==1}
    def orbit(x):
        a,b,c,d=x
        return frozenset(((s*(a+k*b))%n,s*b%n,s*(c+k*d)%2,s*d%2)
                         for s in (-1,1) for k in range(n))
    classes=sorted(set(map(orbit,labels)),key=lambda s:sorted(s))
    index={x:i for i,cs in enumerate(classes) for x in cs}
    units=[a for a in range(1,n) if gcd(a,n)==1]
    def perm(t):
        ans=[]
        for cs in classes:
            a,b,c,d=min(cs)
            images={index[(t*a%n,b,t*c%2,d)] for a,b,c,d in cs}
            assert len(images)==1 # action is well defined on every orbit
            ans.append(images.pop())
        assert len(set(ans))==len(classes)
        return ans
    perms={t:perm(t) for t in units}
    frob=perms[p%n]
    left=set(range(len(classes))); cycles=[]
    while left:
        i=min(left);cy=[]
        while i not in cy:
            cy.append(i);left.remove(i);i=frob[i]
        assert i==cy[0]
        cycles.append(cy)
    allowed=[]
    for k in range(1,degree):
        relevant=[cy for cy in cycles if len(cy)<=k]
        allowed.append([t for t in units if all(perms[t][cy[0]] in cy for cy in relevant)])
    return {'n':n,'p':p,'geometric_cusps':len(classes),
            'frobenius_degrees':sorted(map(len,cycles)),
            'allowed_residues_by_complement_degree':allowed,
            'rational_residue_cusps_not_rational_over_Q':sum(
                len(cy)==1 and any(perms[t][cy[0]]!=cy[0] for t in units) for cy in cycles)}

def main():
    records=[compute(n,p) for n,p in CASES]
    # Independently obtained actual curve cusp signatures.
    assert Counter(records[0]['frobenius_degrees'])=={1:15,5:3}
    lines=['// Generated by cusp_conditions_m2.py; exact Tate cusp permutations.',
           'TateCuspDegrees:=AssociativeArray();',
           'TateCuspAllowed:=AssociativeArray();']
    for r in records:
        key=f'<{r["n"]},{r["p"]}>'
        lines += [f'TateCuspDegrees[{key}]:={r["frobenius_degrees"]};',
                  f'TateCuspAllowed[{key}]:={r["allowed_residues_by_complement_degree"]};']
    (HERE/'data/cusp_conditions_m2.json').write_text(json.dumps(records,indent=2)+'\n')
    (HERE/'data/cusp_conditions_m2.m').write_text('\n'.join(lines)+'\n')
    for r in records:
        print(r['n'],r['p'],dict(Counter(r['frobenius_degrees'])),
              'nonrational lifts among rational residue cusps:',r['rational_residue_cusps_not_rational_over_Q'])
    print('M2_CUSP_CONDITIONS_DONE')

if __name__=='__main__':main()
