/* Small exact genus0 factor for the economical C65 genus21 quotient. */
SetColumns(0);SetMemoryLimit(2*10^9);t0:=Cputime();
AttachSpec("mdmagma/v2/mdmagma.spec");
X:=MDX1(13,GF(2)); C:=Curve(X); F:=FunctionField(C);
assert Genus(C) eq 2;
E:=EllipticCurve(X`_E);P:=E!X`_P;
uv:=TateNormalForm_xy(E,3*P);uvi:=TateNormalForm_xy(E,9*P);
phi3:=iso<C->C|[uv[1],uv[2],F!1],[uvi[1],uvi[2],F!1]:Check:=false>;
G:=AutomorphismGroup(C,[phi3]); assert #G eq 3;
Q,pi:=CurveQuotient(G); assert Genus(Q) eq 0 and Degree(pi) eq 3;
printf "FACTOR13_QUOTIENT genus=0 degree=3 time=%o\n",Cputime(t0);
print Q;
FQ:=FunctionField(Q);
j:=jInvariant(E);jq3:=Pushforward(pi,j);
assert Pullback(pi,jq3) eq j^3; // Pushforward of functions is the NORM.
R0<z0>:=FunctionField(GF(2));
rQ:=hom<FQ->R0|[1/(z0^2+z0),1/z0]>;
function CubeRootRF(f)
    n:=Numerator(f); d:=Denominator(f);
    nf:=Factorization(n); df:=Factorization(d);
    assert &and[e[2] mod 3 eq 0:e in nf cat df];
    nr:=Parent(n)!1; dr:=Parent(d)!1;
    for e in nf do nr *:=e[1]^(e[2] div 3); end for;
    for e in df do dr *:=e[1]^(e[2] div 3); end for;
    return Parent(f)!nr/dr;
end function;
jr:=CubeRootRF(rQ(jq3));
assert Max(Degree(Numerator(jr)),Degree(Denominator(jr))) eq 28;
printf "FACTOR13_J degree=28 time=%o\n",Cputime(t0);
print "FACTOR13_J_FUNCTION",jr;
uq:=FQ.2/FQ.1; assert Degree(uq) eq 1;
mu:=rQ(uq);
assert Max(Degree(Numerator(mu)),Degree(Denominator(mu))) eq 1;
print "FACTOR13_PARAMETER_CHANGE",mu;
uv2:=TateNormalForm_xy(E,2*P);uvi2:=TateNormalForm_xy(E,7*P);
phi2:=iso<C->C|[uv2[1],uv2[2],F!1],[uvi2[1],uvi2[2],F!1]:Check:=false>;
G2:=AutomorphismGroup(C,[phi2]); assert #G2 eq 6;
tau2:=G2!phi2;
up:=Pullback(pi,uq);
uq2cube:=Pushforward(pi,tau2(up));
assert Pullback(pi,uq2cube) eq tau2(up)^3;
sigmu:=CubeRootRF(rQ(uq2cube));
num:=Numerator(mu); den:=Denominator(mu);
sigma:=(Coefficient(den,0)*sigmu-Coefficient(num,0))/(Coefficient(num,1)-Coefficient(den,1)*sigmu);
assert Evaluate(mu,sigma) eq sigmu;
assert Evaluate(sigma,sigma) eq R0.1 and sigma ne R0.1;
assert Evaluate(jr,sigma) eq jr;
print "FACTOR13_AF",R0;
print "FACTOR13_AF_J",jr;
print "FACTOR13_AF_INVOLUTION",sigma;
a1,a2,a3,a4,a6:=Explode(aInvariants(E));
Araw:=(a2+a3/a1)/a1^2;
tau3:=G!phi3;
Atr:=Araw+tau3(Araw)+(tau3^2)(Araw);
assert tau3(Atr) eq Atr;
Acube:=Pushforward(pi,Atr);
assert Pullback(pi,Acube) eq Atr^3;
Abar:=CubeRootRF(rQ(Acube));
assert jr eq (z0^16+z0^4+1)/(z0^28+z0^25+z0^24+z0^21+z0^20+z0^17+z0^16+z0^13);
assert Abar eq (z0^7+z0^6+z0^2+z0)/(z0^4+z0+1);
assert mu eq z0+1;
assert Evaluate(jr,up+1) eq j;
assert Evaluate(Abar,up+1) eq Atr;
print "FACTOR13_TWIST_PARAMETER",Abar;
VV<v>:=PolynomialRing(R0);
rr:=Roots(v^2+v+Evaluate(Abar,z0+1)+Abar);
assert #rr eq 2;
qU:=rr[1][1];
assert Evaluate(qU,z0+1)+qU eq 1;
print "FACTOR13_TWIST_LIFT",qU;
printf "FACTOR13_DONE time=%o\n",Cputime(t0);
quit;
