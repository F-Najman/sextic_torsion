from fractions import Fraction as Fr
from math import gcd

def primes(n):
    out, p = [], 2
    while p * p <= n:
        if n % p == 0:
            out.append(p)
            while n % p == 0:
                n //= p
        p += 1
    if n > 1:
        out.append(n)
    return out

def index_gamma1(n):           # [PSL_2(Z) : Gamma_1(n)-bar], n > 2
    r = Fr(n * n, 2)
    for p in primes(n):
        r *= Fr(p * p - 1, p * p)
    return r

def order_in_delta(a, n):      # order of <a> in (Z/n)^x / {+-1}
    k, x = 1, a % n
    while x not in (1, n - 1):
        x = x * a % n; k += 1
    return k

