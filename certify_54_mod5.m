/* certify_54_mod5.m -- the computations in the proof that Z/54Z is not a sextic torsion group,
   on Y = X_1(27) over F_5.

   Setting of the proof: E has a point P of order 54 over a sextic field K, and Z is the
   non-cuspidal part of the reduction modulo 5 of the trace divisor of (E,2P) on Y. As J_1(27)(Q)
   is generated by Q-rational cuspidal divisor classes, Lemma 7.1 of the paper gives
   [Z - deg(Z) c0] in G, the subgroup of J(F_5) generated by the classes of the closed cusps.
   At a prime of K above 5 at which E has good reduction, the reduction of E has a point of
   order 2 over the residue field.  With the place counts checked below this leaves
       Z = 3y      with y quadratic,
       Z = y       with 3 <= deg y <= 6,
       Z = y + y'  with y and y' cubic (possibly equal),
   where in the last two cases the elliptic curves of y and y' have a point of order 2 over the
   residue field.  Every such Z is tested, without reduction by the diamond operators.  The
   script checks that the Z that pass are exactly the y + y' with y, y' in the set S of cubic
   places whose elliptic curves have j-invariant 2, that #S = 3 and that S is one orbit of the
   diamond operators.  Finally it checks that no curve 2-isogenous to one with j-invariant 2 has
   j-invariant in F_5: for E0: y^2 = x^3+x+1, which has j-invariant 2, the quotient by (r,0),
   where r^3+r+1 = 0, has j-invariant 1/(r^2+r+1) = 2r^2+r+4.

   Checks of the input: the order of J(F_5) agrees with the Frobenius polynomial of J_1(27); G
   has the invariants [3,3,52497] of J_1(27)(Q) [DEHMZ, Corollary 4.14 and Table 2], on which
   reduction modulo 5 is injective; and the numbers of closed places of X_1(54) over F_5 implied
   by the numbers of points of order 2 agree with the independent count in count_short_sieves.m
   (logs/counts/short_sieves.log).  The place counts of Y are also checked independently by
   count_27_gl2.m.

   Usage: magma -n -b certify_54_mod5.m */
SetColumns(0);
if not assigned MemGB then MemGB:=8; elif Type(MemGB) eq MonStgElt then MemGB:=StringToInteger(MemGB); end if;
SetMemoryLimit(MemGB*10^9);
AttachSpec("mdmagma/v2/mdmagma.spec");
t0:=Cputime();
F:=GF(5);
X:=MDX1(27,F);C:=Curve(X);
assert Genus(C) eq 13;

/* The class group, the closed cusps and the group G. */
Cl,m1,m2:=ClassGroup(C);
assert #[e:e in Invariants(Cl)|e eq 0] eq 1;
fr:=FrobeniusPolynomial(JOne(27),5);
assert Degree(fr) eq 26;
jorder:=Integers()!Evaluate(fr,1);
assert &*[e:e in Invariants(Cl)|e ne 0] eq jorder;
cusps:=Cusps(X);
orbits:=[Type(O) eq PlcCrvElt select Divisor(O) else O:O in CuspOrbitsQ(X)];
// 5 is a primitive root modulo 27, so each Galois orbit of cusps reduces to one closed cusp
assert #cusps eq #orbits and &and[#Support(O) eq 1:O in orbits];
c0:=[c:c in cusps|Degree(c) eq 1][1];
cl:=func<D|m2(D-Degree(D)*Divisor(c0))>;
G:=sub<Cl|[cl(Divisor(c)):c in cusps]>;
assert Invariants(G) eq [3,3,52497];
printf "C54_MOD5_GROUPS cusp_degrees=%o J=%o G=%o index=%o time=%o\n",
 Sort([Degree(c):c in cusps]),[e:e in Invariants(Cl)|e ne 0],Invariants(G),jorder div #G,Cputime(t0);

/* The non-cuspidal places of degree at most 6 and their points of order 2. */
function TwoTorsionCount(X,x)
 E:=EllipticCurve(X,x);
 b:=bInvariants(E);
 R<t>:=PolynomialRing(BaseRing(E));
 r:=#Roots(4*t^3+b[1]*t^2+2*b[2]*t+b[3]);
 n:=#E;
 assert n mod 27 eq 0 and r in {0,1,3} and (r gt 0) eq IsEven(n);
 return r;
end function;
places:=[NoncuspidalPlaces(X,d):d in [1..6]];
assert [#s:s in places] eq [0,9,57,171,612,2700];
roots:=[[TwoTorsionCount(X,x):x in places[d]]:d in [1..6]];
two:=[[places[d][i]:i in [1..#places[d]]|roots[d][i] gt 0]:d in [1..6]];
assert [#s:s in two] eq [0,0,30,171,396,1890];
// closed places of X_1(54) of degree d: one for each point of order 2 over k(y) above y of
// degree d, one above each y of degree d/2 with exactly one, one above each y of degree d/3 with none
n54:=[];
for d in [1..6] do
 n:=&+([0] cat roots[d]);
 if d mod 2 eq 0 then n+:=#[r:r in roots[d div 2]|r eq 1];end if;
 if d mod 3 eq 0 then n+:=#[r:r in roots[d div 3]|r eq 0];end if;
 Append(~n54,n);
end for;
assert n54 eq [0,0,54,261,612,3033];
printf "C54_MOD5_PLACES counts=%o with_point_of_order_2=%o X1_54_counts=%o time=%o\n",
 [#s:s in places],[#s:s in two],n54,Cputime(t0);

/* The class test for every possible Z. */
survivors:=[];
passed:=0;
for x in places[2] do
 if cl(3*Divisor(x)) in G then passed+:=1;Append(~survivors,[x,x,x]);end if;
end for;
printf "C54_MOD5_TEST type=3y tested=%o passed=%o time=%o\n",#places[2],passed,Cputime(t0);
for d in [3..6] do
 passed:=0;
 for x in two[d] do
  if cl(Divisor(x)) in G then passed+:=1;Append(~survivors,[x]);end if;
 end for;
 printf "C54_MOD5_TEST type=y degree=%o tested=%o passed=%o time=%o\n",d,#two[d],passed,Cputime(t0);
end for;
q3:=[cl(Divisor(x)):x in two[3]];
tested:=0;passed:=0;
for i in [1..#q3] do
 for j in [i..#q3] do
  tested+:=1;
  if q3[i]+q3[j] in G then passed+:=1;Append(~survivors,[two[3][i],two[3][j]]);end if;
 end for;
end for;
assert tested eq Binomial(#q3+1,2);
printf "C54_MOD5_TEST type=y+y' tested=%o passed=%o time=%o\n",tested,passed,Cputime(t0);

/* The survivors are the sums of two points of S. */
S:=[x:x in places[3]|jInvariant(X,x) eq 2];
assert #S eq 3 and &and[x in two[3]:x in S];
assert Seqset(DiamondOrbit(X,S[1])) eq Seqset(S);
assert #survivors eq 6 and &and[#s eq 2:s in survivors];
assert {Seqset(s):s in survivors} eq {{a,b}:a,b in S};
printf "C54_MOD5_SURVIVORS count=%o all_in_S=true S_degrees=%o S_j=2 S_is_one_diamond_orbit=true time=%o\n",
 #survivors,[Degree(x):x in S],Cputime(t0);

/* No curve 2-isogenous to a curve with j-invariant 2 has j-invariant in F_5. */
E0:=EllipticCurve([F|1,1]);
assert jInvariant(E0) eq 2 and #E0 eq 9;
R5<t>:=PolynomialRing(F);
assert IsIrreducible(t^3+t+1);
k:=GF(125);
E0k:=BaseChange(E0,k);
assert #E0k eq 108;
Rk<u>:=PolynomialRing(k);
rs:=[r[1]:r in Roots(u^3+u+1)];
assert #rs eq 3;
for r in rs do
 j:=jInvariant(IsogenyFromKernel(E0k,u-r));
 assert j eq 1/(r^2+r+1) and j eq 2*r^2+r+4 and j^5 ne j;
 // the models in the paper: moving (r,0) to (0,0) gives y^2 = x(x^2+ax+b) with a = 3r and
 // b = 3r^2+1, and its quotient by <(0,0)> is y^2 = x(x^2-2ax+a^2-4b) = x(x^2+4rx+2r^2+1)
 M:=EllipticCurve([k|0,3*r,0,3*r^2+1,0]);
 Q:=EllipticCurve([k|0,4*r,0,2*r^2+1,0]);
 assert IsIsomorphic(M,E0k) and IsIsomorphic(Q,IsogenyFromKernel(M,u)) and jInvariant(Q) eq j;
end for;
for x in S do
 E:=EllipticCurve(X,x);
 assert IsIsomorphic(E,BaseChange(E0,BaseRing(E)));
 W:=WeierstrassModel(E);
 Rw<w>:=PolynomialRing(BaseRing(W));
 ws:=[r[1]:r in Roots(w^3+Coefficients(W)[4]*w+Coefficients(W)[5])];
 assert #ws eq 3;
 for r in ws do
  j:=jInvariant(IsogenyFromKernel(W,w-r));
  assert j^5 ne j;
 end for;
end for;
printf "C54_MOD5_ISOGENY E0_j=2 E0_points_F5=9 E0_points_F125=108 paper_models=true S_isomorphic_to_E0=true isogenous_j_outside_F5=true time=%o\n",Cputime(t0);
printf "C54_MOD5_CERTIFICATE_DONE complete=true time=%o\n",Cputime(t0);
quit;
